#!/usr/bin/env python3
"""Generate the firmware's immutable replay table from the accepted mock extract."""

import argparse
import hashlib
import json
from decimal import Decimal
from pathlib import Path

CLUSTER = Path(__file__).resolve().parents[1]
REPO = CLUSTER.parents[1]
SOURCE = REPO / "dashboard/esp32p4-mocks/data.json"
OUTPUT = CLUSTER / "generated/replay_data.hpp"
RECORDED = (
    "rpm", "map", "baro", "oil", "coolant", "battery", "tps", "afr",
    "target", "advance", "pw", "duty", "iat", "ego", "warmup",
)
SIMULATED = ("speed", "fuel", "oiltemp")


def format_float(value: Decimal) -> str:
    literal = format(value, "f")
    if "." not in literal:
        literal += ".0"
    return f"{literal}f"


def generate() -> str:
    contents = SOURCE.read_bytes()
    source = json.loads(contents, parse_float=Decimal, parse_int=Decimal)
    rows = [dict(zip(source["columns"], row, strict=True)) for row in source["samples"]]
    if len(rows) != 576 or len(rows) != source["source"]["sample_count"]:
        raise ValueError("unexpected accepted replay sample count")
    start = rows[0]["time"]
    previous_ms = -1
    samples = []
    offsets = []
    for row in rows:
        offset = (row["time"] - start) * 1000
        if offset != int(offset) or offset < previous_ms:
            raise ValueError("replay sample timestamps must be nondecreasing milliseconds")
        previous_ms = int(offset)
        offsets.append(previous_ms)
        if any(row[name] is not None for name in SIMULATED):
            raise ValueError("simulated fields must be absent from the recorded rows")
        if any(not isinstance(row[name], Decimal) or not row[name].is_finite()
               for name in RECORDED):
            raise ValueError("recorded field missing or invalid")
        sync = row["sync"]
        if sync not in range(4):
            raise ValueError("invalid recorded sync status")
        fields = [str(previous_ms), *(format_float(row[name]) for name in RECORDED), str(int(sync))]
        samples.append("    {" + ", ".join(fields) + "},")
    if previous_ms != 54425:
        raise ValueError("unexpected accepted replay duration")
    first = 0
    max_history_rows = 0
    for last, milliseconds in enumerate(offsets):
        while milliseconds - offsets[first] > 8000:
            first += 1
        max_history_rows = max(max_history_rows, last - first + 1)
    columns = "\n".join(f"    float {name};" for name in RECORDED)
    samples_text = "\n".join(samples)
    return f"""// Generated by tools/generate_replay.py from dashboard/esp32p4-mocks/data.json.
// Accepted extract SHA-256: {hashlib.sha256(contents).hexdigest()}
#pragma once

#include <cstdint>

namespace cluster::replay_data {{

inline constexpr uint32_t history_window_ms = 8000;
inline constexpr uint32_t max_history_rows = {max_history_rows};

struct Sample {{
    uint32_t offset_ms;
{columns}
    uint8_t sync;
}};

inline constexpr Sample samples[] = {{
{samples_text}
}};

}} // namespace cluster::replay_data
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the checked-in table")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_bytes() != expected.encode("utf-8"):
            parser.exit(1, f"{OUTPUT.relative_to(REPO)} needs regeneration\n")
    else:
        OUTPUT.write_bytes(expected.encode("utf-8"))


if __name__ == "__main__":
    main()
