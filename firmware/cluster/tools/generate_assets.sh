#!/bin/sh
set -eu
DEPS=${TURBOEXO_DEPS:?Set TURBOEXO_DEPS to the persistent dependency directory}
CONV="$DEPS/font-converter/node_modules/.bin/lv_font_conv"
FONT="$DEPS/lvgl-9.5.0/scripts/built_in_font/Montserrat-Medium.ttf"
OUT="$(CDPATH= cd -- "$(dirname "$0")/../assets" && pwd)"
for size in 64 96 144 220; do
  "$CONV" --font "$FONT" --size "$size" --bpp 4 --format lvgl --no-compress --symbols '0123456789.,+-' --lv-font-name "cluster_num_$size" --output "$OUT/cluster_num_$size.c"
done
for size in 26 34; do
  "$CONV" --font "$FONT" --size "$size" --bpp 4 --format lvgl --no-compress --range 32-126,176,189,215 --lv-font-name "cluster_text_$size" --output "$OUT/cluster_text_$size.c"
done
# Converter embeds machine-specific paths in its informational command comment.
python3 - "$OUT" <<'PYCODE'
from pathlib import Path
import sys
for path in Path(sys.argv[1]).glob('cluster_*.c'):
    if path.name == 'cluster_icons.c':
        continue
    lines = path.read_text().splitlines()
    lines = [' * Generated by tools/generate_assets.sh (Montserrat, lv_font_conv 1.5.3)' if line.startswith(' * Opts:') else line for line in lines]
    path.write_text('\n'.join(line.rstrip() for line in lines).rstrip() + '\n')
PYCODE
