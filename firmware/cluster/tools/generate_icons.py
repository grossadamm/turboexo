#!/usr/bin/env python3
"""Rasterize the licensed stock SVGs into LVGL ARGB8888 images (rsvg-convert, Pillow)."""
import io
import pathlib
import subprocess
from PIL import Image
root = pathlib.Path(__file__).resolve().parent.parent / 'assets'
output = ['/* Generated by tools/generate_icons.py from the licensed stock SVGs. */', '#include <lvgl.h>']
for name in ('oil-can', 'thermometer', 'fuel', 'gauge'):
    svg = (root / (name + '.svg')).read_text().replace('currentColor', '#a9b5af')
    if name == 'oil-can':
        svg = svg.replace('<svg ', '<svg fill="#a9b5af" ', 1)
    png = subprocess.run(['rsvg-convert', '-w', '32', '-h', '32'], input=svg.encode(), capture_output=True, check=True).stdout
    img = Image.open(io.BytesIO(png)).convert('RGBA')
    data = bytearray()
    for r, g, b, a in img.getdata():
        data.extend((b, g, r, a))
    ident = 'cluster_icon_' + name.replace('-', '_')
    output.append('LV_ATTRIBUTE_MEM_ALIGN static const unsigned char ' + ident + '_pixels[] = {')
    for start in range(0, len(data), 24):
        output.append('    ' + ','.join(str(x) for x in data[start:start+24]) + ',')
    output.extend(('};', 'const lv_image_dsc_t ' + ident + ' = {',
        ' .header = { .cf = LV_COLOR_FORMAT_ARGB8888, .w = 32, .h = 32, .stride = 128 },',
        ' .data_size = sizeof(' + ident + '_pixels), .data = ' + ident + '_pixels', '};'))
(root / 'cluster_icons.c').write_text('\n'.join(output) + '\n')
